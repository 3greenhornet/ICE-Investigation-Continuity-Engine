"""benchmark/runner.py — Run the ICE on benchmark cases.

Owner:      ICE revamp, Part 4 §17.2 (benchmark runner); REBUILT by the
            Hari ICE "addition and improvements" pass (P0: "Fix evaluation
            before expanding capabilities").
Purpose:    load_case() materializes a benchmark case directory as a fresh
            case; run_engine_on_case() drives the full engine over it and
            returns per-case metrics; run_all_cases() sweeps every case
            directory with fault isolation.

P0 REBUILD — what changed and why (second-pass audit: "The primary and
secondary hypotheses are also supplied from hidden_resolution.json to the
engine before ranking ... some of its scores are weak proxies"):
    * NO ANSWER LEAKAGE (default). The engine receives ONLY the problem
      definition + evidence. Hypotheses are GENERATED by the induction
      engine (deterministic offline path when no LLM is configured — the
      same engine capability, not a benchmark special case).
      seed_hypotheses_from_resolution=True preserves the OLD seeding
      behavior for legacy comparison runs only.
    * The hidden resolution is opened AFTER the engine run, exclusively by
      the evaluator (this module's metric-gathering tail).
    * Contradiction detection records the actual PAIRS (claim id pairs),
      so metrics can do pair matching instead of count comparison.
    * Per-case results now carry: ranked top-3 hypothesis statements,
      detected contradiction pairs, executed-action outcomes, calibration
      inputs (leading confidence + whether it matched the root cause),
      LLM usage from the ledger, and per-action evidence production —
      the inputs the rebuilt metrics need.
Legacy behavior for ablation/baselines (B4-B6) is preserved: they call
run_engine_on_case with its defaults, which are now the honest ones.
"""

