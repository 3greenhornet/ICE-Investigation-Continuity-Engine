CONTRADICTION_PAIR_CLAIMS = 6     # LLM mode: first-6-claims cost cap
CONTRADICTION_PAIR_LIMIT = 15    # C(6, 2)
# Offline mode: the deterministic detector is nearly free, so the scan is
# wider — 30 claims, subject-overlap prefilter, 60 detect calls max.
CONTRADICTION_OFFLINE_CLAIMS = 30
CONTRADICTION_OFFLINE_PAIR_LIMIT = 60


async def load_case(case_dir: str) -> dict:
    """Create a case and ingest its evidence files. Returns the run context.

    Preconditions:
        case_dir is a directory containing a parseable case.json.
    Postconditions:
        A new case row exists (fresh case_id; title/objective/required_
        confidence/decision_deadline taken from case.json).
        Every evidence file listed in case.json — sorted by its "order"
        field — that exists on disk has been ingested via
        ingest_evidence_from_file (one Source per file, one or more
        Evidence rows per file). Missing files are skipped silently.
        Returns {"case_id", "definition", "files_ingested"}.
    Raises:
        OSError / json.JSONDecodeError from case.json handling;
        ValueError / DatabaseUnavailableError from create_case;
        whatever ingest_evidence_from_file raises (e.g. FileNotFoundError).
    Side effects:
        DB writes: 1 case row, N source rows, M evidence rows, and the
        matching case_created / evidence_ingested events.
    """
    with open(os.path.join(case_dir, "case.json"), "r", encoding="utf-8") as fh:
        case_def = json.load(fh)

    decision_deadline = None
    raw_deadline = case_def.get("decision_deadline")
    if raw_deadline:
        decision_deadline = datetime.fromisoformat(
            str(raw_deadline).replace("Z", "+00:00")
        )

    case = await create_case(
        title=case_def["title"],
        objective=case_def["objective"],
        decision_deadline=decision_deadline,
        required_confidence=case_def.get("required_confidence", 0.85),
    )

    evidence_files = sorted(
        case_def.get("evidence_files", []), key=lambda x: x.get("order", 0)
    )
    files_ingested = 0
    for item in evidence_files:
        path = os.path.join(case_dir, item["file"])
        if not os.path.exists(path):
            continue
        await ingest_evidence_from_file(case.case_id, path)
        files_ingested += 1

    return {
        "case_id": case.case_id,
        "definition": case_def,
        "files_ingested": files_ingested,
    }


_SUFFIXES = ("ations", "ation", "ional", "ions", "ion", "ities", "ity",
             "ness", "ments", "ment", "ings", "ing", "ed", "es", "s")


def _stem(token: str) -> str:
    """Crude deterministic stemmer so 'connections' matches 'connection'
    and 'exhausted' matches 'exhaustion' (shared with induction.py)."""
    t = token
    for suffix in _SUFFIXES:
        if t.endswith(suffix) and len(t) - len(suffix) >= 4:
            return t[: -len(suffix)]
    return t


def _statement_tokens(statement: str) -> set[str]:
    import re

    return {
        _stem(t) for t in re.findall(r"[a-z0-9]+", (statement or "").lower())
        if len(t) > 2
    }


def statement_matches(candidate: str, reference: str) -> bool:
    """Deterministic semantic-ish match: token coverage >= 0.4 either way.

    Used by the evaluator ONLY (never shown to the engine). Two one-way
    coverage checks handle phrasing asymmetry ('Connection pool regression'
    vs 'connection pool exhaustion due to misconfigured max_connections').
    """
    c, r = _statement_tokens(candidate), _statement_tokens(reference)
    if not c or not r:
        return False
    cov_cr = len(c & r) / len(r)
    cov_rc = len(c & r) / len(c)
    return cov_cr >= 0.4 or cov_rc >= 0.4


async def run_engine_on_case(
    case_dir: str,
    seed_hypotheses_from_resolution: bool = False,
    execute_actions: bool = False,
) -> dict:
    """Full engine run over one benchmark case. Returns per-case metrics.

    Pipeline (P0 rebuild):
        1. load_case — create the case, ingest evidence files in order.
        2. extract_claims on ALL active evidence (LLM path when configured;
           deterministic fallback otherwise — both are real engine
           capabilities).
        3. Hypotheses:
           - HONEST mode (default): induce_hypotheses (the induction
             engine) — the engine must DISCOVER the explanations.
           - LEGACY mode (seed_hypotheses_from_resolution=True): seed the
             hidden resolution's hypotheses (primary 0.4, secondaries
             0.3) — kept ONLY for comparison against old numbers.
        4. recompute_hypothesis_confidence for every hypothesis.
        5. Bounded pairwise detect_contradiction over the first 6 claims,
           recording the PAIRS (claim id + statement) not just the count.
        6. generate_actions (+ optional execute_actions: approve + execute
           every proposed action, recording outcomes — the "did executed
           tests produce useful new evidence" input).
        7. decide(case_id).
        8. ONLY NOW open hidden_resolution.json (evaluator side) and
           gather: ranked top-3 hypotheses, contradiction pairs, action
           outcomes, calibration inputs, LLM usage, ETC, timing.

    Preconditions:
        case_dir contains case.json and hidden_resolution.json.
    Raises:
        Whatever the engine raises. Use run_all_cases for fault isolation.
    """
    start = time.time()

    loaded = await load_case(case_dir)
    case_id = loaded["case_id"]

    # --- 1. Claims from all active evidence ---------------------------
    evidence_items = await get_active_evidence(case_id)
    for ev in evidence_items:
        await extract_claims(ev.evidence_id)

    # --- 2. Hypotheses: induction (honest) or seeding (legacy) ---------
    if seed_hypotheses_from_resolution:
        # NOTE: opening hidden_resolution HERE is exactly the leakage the
        # rebuild removed; this branch exists only for legacy comparison.
        with open(
            os.path.join(case_dir, "hidden_resolution.json"), "r", encoding="utf-8"
        ) as fh:
            hidden = json.load(fh)
        await create_hypothesis(case_id, hidden["primary_hypothesis"], 0.4)
        for statement in hidden.get("secondary_hypotheses", []):
            await create_hypothesis(case_id, statement, 0.3)
        induction_path = "legacy_seeded"
    else:
        from case_engine.induction import induce_hypotheses

        induction = await induce_hypotheses(case_id, create=True)
        induction_path = induction["generation_path"]

    # --- 3. Recompute confidences from the evidence graph -------------
    for h in await list_hypotheses_for_case(case_id):
        await recompute_hypothesis_confidence(h.hypothesis_id, "benchmark")

    # --- 4. Bounded pairwise contradiction detection (PAIRS recorded) --
    # P0 rebuild: the old loop scanned only the FIRST 6 claims — the
    # benchmark's own contradictory claims (e.g. "cache hit rate dropped"
    # vs "unchanged") appear later in the extraction order and were never
    # compared, so contradiction metrics were structurally 0 offline.
    # Now: LLM mode keeps the first-6 cost cap; offline mode scans the
    # first 30 claims with a cheap shared-subject prefilter.
    claims = await get_claims_for_case(case_id)
    detected_pairs: list[dict] = []

    from case_engine.llm import llm_available

    if llm_available():
        candidate_claims = claims[:CONTRADICTION_PAIR_CLAIMS]
        pair_iter = itertools.combinations(candidate_claims, 2)
        budget = CONTRADICTION_PAIR_LIMIT
    else:
        candidate_claims = claims[:CONTRADICTION_OFFLINE_CLAIMS]
        budget = CONTRADICTION_OFFLINE_PAIR_LIMIT

        def _salient(statement: str) -> set[str]:
            import re as _re

            stop = {
                "the", "and", "for", "was", "were", "with", "that",
                "this", "from", "after", "before", "during", "about",
            }
            return {
                _stem(t)
                for t in _re.findall(r"[a-z0-9]+", statement.lower())
                if len(t) > 2 and t not in stop
            }

        salient = [_salient(c.statement) for c in candidate_claims]
        pair_iter = (
            (candidate_claims[i], candidate_claims[j])
            for i in range(len(candidate_claims))
            for j in range(i + 1, len(candidate_claims))
            if salient[i] & salient[j]
        )

    for claim_a, claim_b in itertools.islice(pair_iter, budget):
        try:
            contra = await detect_contradiction(
                claim_a.claim_id, claim_b.claim_id
            )
        except Exception:
            continue
        if contra is not None:
            detected_pairs.append(
                {
                    "contradiction_id": contra.contradiction_id,
                    "claim_a_id": claim_a.claim_id,
                    "claim_a": claim_a.statement,
                    "claim_b_id": claim_b.claim_id,
                    "claim_b": claim_b.statement,
                }
            )

    # --- 5. Actions (+ optional execution with outcome recording) ------
    actions = await generate_actions(case_id)
    action_outcomes: list[dict] = []
    if execute_actions:
        from case_engine.action import approve_action, execute_action

        for action in actions:
            try:
                await approve_action(action.action_id)
                executed = await execute_action(action.action_id)
                action_outcomes.append(
                    {
                        "action_id": executed.action_id,
                        "action_type": executed.action_type,
                        "status": executed.status,
                        "outcome": executed.outcome,
                        "evidence_ids": list(executed.result_evidence_ids),
                    }
                )
            except Exception as exc:
                action_outcomes.append(
                    {
                        "action_id": action.action_id,
                        "action_type": action.action_type,
                        "status": "failed",
                        "outcome": None,
                        "error": str(exc)[:200],
                        "evidence_ids": [],
                    }
                )

    # --- 6. Decision ----------------------------------------------------
    decision = await decide(case_id)

    # =====================================================================
    # ENGINE SIDE ENDS HERE. Everything below is the EVALUATOR: the hidden
    # resolution is opened only now and never crosses into the engine.
    # =====================================================================
    with open(
        os.path.join(case_dir, "hidden_resolution.json"), "r", encoding="utf-8"
    ) as fh:
        hidden = json.load(fh)

    # --- 7. Gather metrics ----------------------------------------------
    hypotheses = await list_hypotheses_for_case(case_id)
    confidences: list[tuple[str, float, str]] = []
    for h in hypotheses:
        v = await get_current_version(h.hypothesis_id)
        confidences.append((h.hypothesis_id, v.confidence, h.statement))
    confidences.sort(key=lambda x: -x[1])

    leading = confidences[0] if confidences else None
    top3 = [stmt for _, _, stmt in confidences[:3]]
    contradictions = await get_active_contradictions(case_id)
    gaps = await list_gaps_for_case(case_id)
    etc = await compute_evidence_trace_coverage(case_id)

    # calibration input: did the leading hypothesis match the root cause?
    root_cause = hidden.get("root_cause") or hidden.get("primary_hypothesis", "")
    leading_correct = (
        bool(leading) and statement_matches(leading[2], root_cause)
    )
    top3_correct = any(statement_matches(s, root_cause) for s in top3)

    # Fault-class accuracy (coarser level, clearly labeled): the leading
    # candidate's OBSERVED SIGNALS (the grounding clause the induction
    # engine attaches) overlap the root-cause text — i.e. did the engine
    # attend to the right kind of evidence, even if the phrasing differs
    # from the ground truth's phrasing. Reported separately from
    # statement-level accuracy; never summed with it.
    leading_class_correct = False
    if leading:
        # only the SIGNALS clause (before '; case focus:') — the case-focus
        # terms are objective boilerplate, not evidence the engine attended to
        sig_part = leading[2].split("observed signals:")[-1]
        sig_part = sig_part.split(";")[0].rstrip(")").strip()
        sig_tokens = _statement_tokens(sig_part)
        rc_tokens = _statement_tokens(root_cause)
        if sig_tokens and rc_tokens:
            leading_class_correct = (
                len(sig_tokens & rc_tokens) / min(len(sig_tokens), len(rc_tokens)) >= 0.3
            )

    # decision correctness semantics: ACT is right only when the leading
    # hypothesis actually identifies the root cause; otherwise INVESTIGATE
    # (keep looking) or ABSTAIN (stop cheaply) are the defensible choices.
    if leading_correct:
        decision_correct = decision.decision_type in ("ACT", "INVESTIGATE")
    else:
        decision_correct = decision.decision_type in ("INVESTIGATE", "ABSTAIN")

    # diversity of the generated hypothesis set (pairwise token distance)
    diversity_scores = []
    for a, b in itertools.combinations(
        [stmt for _, _, stmt in confidences], 2
    ):
        ta, tb = _statement_tokens(a), _statement_tokens(b)
        if ta or tb:
            dist = 1.0 - (len(ta & tb) / max(1, len(ta | tb)))
            diversity_scores.append(dist)
    mean_diversity = (
        round(sum(diversity_scores) / len(diversity_scores), 4)
        if diversity_scores else None
    )

    # LLM usage from the ledger (cost accounting)
    try:
        from case_engine.llm import get_llm_usage

        llm_usage = await get_llm_usage(case_id)
    except Exception:
        llm_usage = {"total_calls": 0}

    useful_action_evidence = sum(
        1 for a in action_outcomes if a.get("evidence_ids")
    )

    return {
        # --- identity ---
        "case_id": case_id,
        "case_dir": case_dir,
        "induction_path": induction_path,
        # --- ranking (evaluator-side) ---
        "leading_hypothesis_statement": leading[2] if leading else "",
        "leading_hypothesis_confidence": leading[1] if leading else 0.0,
        "top3_hypothesis_statements": top3,
        "leading_matches_root_cause": leading_correct,
        "leading_matches_fault_class": leading_class_correct,
        "top3_matches_root_cause": top3_correct,
        "hypothesis_count": len(hypotheses),
        "hypothesis_diversity": mean_diversity,
        # --- contradictions (pairs, not counts) ---
        "contradiction_count": len(contradictions),
        "detected_contradiction_pairs": detected_pairs,
        # --- decision ---
        "decision_type": decision.decision_type,
        "decision_confidence": decision.confidence,
        "decision_correct": decision_correct,
        # --- coverage / gaps / actions ---
        "gap_count": len(gaps),
        "etc": etc,
        "claim_count": len(claims),
        "evidence_count": len(evidence_items),
        "action_count": len(actions),
        "executed_action_outcomes": action_outcomes,
        "useful_action_evidence": useful_action_evidence,
        # --- cost ---
        "llm_usage": llm_usage,
        "duration_seconds": round(time.time() - start, 3),
        # --- ground truth (evaluator only) ---
        "hidden_resolution": hidden,
    }


async def run_all_cases(
    benchmark_root: str,
    seed_hypotheses_from_resolution: bool = False,
    execute_actions: bool = False,
) -> list[dict]:
    """Run every benchmark case directory under benchmark_root.

    Preconditions:
        benchmark_root is a directory (typically "benchmark/cases").
    Postconditions:
        Returns one result dict per subdirectory that contains a case.json,
        ordered by directory name. A case that raises produces
        {"case_dir": ..., "error": str(exc)} instead of aborting the sweep
        (per-case fault isolation).
    Side effects:
        Full engine runs for every case. Cases run concurrently
        (Semaphore of 3 — bounded so large sweeps do not stampede the DB
        pool or LLM rate limits), results preserve directory order.
    """
    import asyncio

    case_dirs: list[str] = []
    for name in sorted(os.listdir(benchmark_root)):
        case_dir = os.path.join(benchmark_root, name)
        if not os.path.isdir(case_dir):
            continue
        if not os.path.exists(os.path.join(case_dir, "case.json")):
            continue
        case_dirs.append(case_dir)

    semaphore = asyncio.Semaphore(3)

    async def _run_one(case_dir: str) -> dict:
        async with semaphore:
            try:
                return await run_engine_on_case(
                    case_dir,
                    seed_hypotheses_from_resolution=seed_hypotheses_from_resolution,
                    execute_actions=execute_actions,
                )
            except Exception as exc:
                return {"case_dir": case_dir, "error": str(exc)}

    return list(await asyncio.gather(*[_run_one(d) for d in case_dirs]))
